/// <reference types="vitest" />
import { defineConfig, type Plugin } from 'vite';
import react from '@vitejs/plugin-react';
import { fileURLToPath, URL } from 'node:url';
import { readdirSync, statSync } from 'node:fs';
import { join, relative } from 'node:path';

function listPublic(dir: string, root = dir): string[] {
  return readdirSync(dir).flatMap((name) => {
    const full = join(dir, name);
    return statSync(full).isDirectory() ? listPublic(full, root) : [relative(root, full).split('\\').join('/')];
  });
}

/**
 * Emits dist/sw.js with a precache list of every built file, so the whole app
 * (including the lazily-loaded PDF generator, fonts and emoji) works offline after the first visit.
 */
function serviceWorkerPlugin(): Plugin {
  return {
    name: 'catering-sw',
    apply: 'build',
    generateBundle(_opts, bundle) {
      const publicDir = fileURLToPath(new URL('./public', import.meta.url));
      const files = [...Object.keys(bundle), ...listPublic(publicDir)].filter((f) => !f.endsWith('.map') && !f.endsWith('.woff') && f !== 'sw.js');
      const version = Date.now().toString(36);
      const precache = ['./', ...files.map((f) => './' + f)];
      const source = `/* generated by vite.config.ts — do not edit */
const CACHE = 'catering-${version}';
const PRECACHE = ${JSON.stringify(precache)};
self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', (e) => {
  e.waitUntil(
    caches.keys().then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()),
  );
});
self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return; // never cache API calls (Anthropic etc.)
  if (req.mode === 'navigate') {
    // network first for the page, fall back to the cached shell when offline
    e.respondWith(
      fetch(req)
        .then((res) => {
          const copy = res.clone();
          caches.open(CACHE).then((c) => c.put('./', copy));
          return res;
        })
        .catch(() => caches.match('./', { ignoreVary: true }).then((r) => r || caches.match('./index.html', { ignoreVary: true }))),
    );
    return;
  }
  // ignoreVary: hosts may send "Vary: Origin" and module scripts are requested with an Origin header,
  // which would make every precached file miss while offline.
  e.respondWith(
    caches.match(req, { ignoreVary: true }).then(
      (hit) =>
        hit ||
        fetch(req).then((res) => {
          if (res.ok) {
            const copy = res.clone();
            caches.open(CACHE).then((c) => c.put(req, copy));
          }
          return res;
        }),
    ),
  );
});
`;
      this.emitFile({ type: 'asset', fileName: 'sw.js', source });
    },
  };
}

// base './' so the build works on GitHub Pages (any sub-path) and as a static bundle anywhere.
export default defineConfig({
  base: './',
  plugins: [react(), serviceWorkerPlugin()],
  resolve: {
    alias: { '@': fileURLToPath(new URL('./src', import.meta.url)) },
  },
  build: {
    target: 'es2020',
    chunkSizeWarningLimit: 2500,
  },
  test: {
    environment: 'jsdom',
    globals: true,
    setupFiles: ['./src/test/setup.ts'],
    include: ['src/**/*.test.{ts,tsx}'],
  },
});
